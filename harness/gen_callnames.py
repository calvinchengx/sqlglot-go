#!/usr/bin/env python3
"""Ingest the reference's function registries for the port's hand-registered
dialects.

Most dialects' tables are generated whole, and their NamedFunctions set is
the reference's FUNCTIONS and FUNCTION_PARSERS together. A handful of
dialects are registered BY HAND from the neutral table (Oracle, Snowflake,
DAX, PRQL), because growing the generated map for one dialect is a verbosity
regression on all of it -- and that leaves their function names incomplete.

The anonymizer is the one place that has to know every name the reference
treats as a function: it leaves a call's NAME alone only where the reference
would, and anonymizes it otherwise. So the names the hand-registered dialects
add to the neutral set are recorded here, and nothing else is.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import subprocess
import sys

HAND_REGISTERED = ("oracle", "snowflake", "dax", "prql")


def go_set(name: str, names: list[str], indent: str = "\t\t") -> str:
    out = [f'{indent}"{name}": {{']
    for n in names:
        out.append(f'{indent}\t"{n}": {{}},')
    out.append(f"{indent}}},")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sqlglot", required=True, type=pathlib.Path)
    ap.add_argument("--out", default=pathlib.Path("sqlglot/callnames_gen.go"))
    a = ap.parse_args()

    sys.path.insert(0, str(a.sqlglot))
    from sqlglot.dialects import Dialect

    actual = subprocess.check_output(
        ["git", "-C", str(a.sqlglot), "rev-parse", "HEAD"], text=True
    ).strip()

    base = Dialect.get_or_raise(None).parser_class
    neutral = set(base.FUNCTIONS) | set(base.FUNCTION_PARSERS)

    out = [
        "// Code generated by harness/gen_callnames.py from the pinned reference. DO NOT EDIT.",
        "",
        "package sqlglot",
        "",
        "// extraCallNames are the function names a HAND-REGISTERED dialect knows",
        "// and the neutral table does not. The anonymizer consults them so a call",
        "// keeps the name the reference keeps.",
        f"// reference {actual[:12]}",
        "var extraCallNames = map[string]map[string]struct{}{",
    ]
    for name in HAND_REGISTERED:
        parser = Dialect.get_or_raise(name).parser_class
        extra = sorted((set(parser.FUNCTIONS) | set(parser.FUNCTION_PARSERS)) - neutral)
        if not extra:
            continue
        out.append(f'\t"{name}": {{')
        for n in extra:
            out.append(f'\t\t"{n}": {{}},')
        out.append("\t},")
    out.append("}")
    out.append("")

    a.out.write_text("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
